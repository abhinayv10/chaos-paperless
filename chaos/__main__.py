TERMINAL = {s.value for s in TERMINAL_STATES}


def ensure_env() -> None:
    if config.SANDBOX_ENV_FILE.exists():
        return
    config.SANDBOX_ENV_FILE.write_text(
        "# generated by `python -m chaos up` - sandbox-only credentials\n"
        f"PAPERLESS_SECRET_KEY={secrets.token_urlsafe(48)}\n"
        f"PAPERLESS_DB_PASSWORD={secrets.token_urlsafe(18)}\n"
        "PAPERLESS_ADMIN_USER=chaosadmin\n"
        f"PAPERLESS_ADMIN_PASSWORD={secrets.token_urlsafe(18)}\n",
        encoding="utf-8",
    )
    print(f"generated {config.SANDBOX_ENV_FILE}")


def _print_checks(checks) -> bool:
    for c in checks:
        print(f"  [{'PASS' if c.ok else 'FAIL'}] {c.name}: {c.detail}")
    return all(c.ok for c in checks)


def cmd_up(a) -> int:
    d = Docker()
    ok, ver = d.available()
    if not ok:
        print(f"Docker engine not reachable: {ver}\nStart Docker Desktop and retry.")
        return 2
    print(f"docker engine {ver}")
    ensure_env()
    (config.SANDBOX_DIR / "consume").mkdir(exist_ok=True)
    (config.SANDBOX_DIR / "export").mkdir(exist_ok=True)
    print("building netem helper image ...")
    b = d.build_netem_image()
    if b.returncode != 0:
        print(b.stderr[-1500:])
        print("WARNING: netem image build failed; network_latency fault will fail preflight")
    print("starting sandbox (first run pulls images; can take several minutes) ...")
    cp = d.compose("up", "-d", "--wait", "--wait-timeout", "900")
    print(cp.stdout[-2000:], cp.stderr[-3000:])
    if cp.returncode != 0:
        print("compose up failed")
        return 1
    client = PaperlessClient(timeout=10)
    for _ in range(60):
        try:
            client.token()
            break
        except Exception:  # noqa: BLE001
            time.sleep(5)
    else:
        print("Paperless API did not issue a token")
        return 1
    print(f"Paperless-ngx is up at {config.PAPERLESS_URL}  (user {client.username}, password in sandbox/.env)")
    return 0


def cmd_down(a) -> int:
    d = Docker()
    ok, notes = emergency_rollback(d)
    print("pre-teardown rollback:", "verified" if ok else "UNVERIFIED", notes)
    args = ["down", "--remove-orphans"] + (["--volumes"] if a.volumes else [])
    cp = d.compose(*args)
    print(cp.stdout, cp.stderr)
    return cp.returncode


def _engine() -> Engine:
    return Engine(Store(), Docker(), PaperlessClient)


def cmd_status(a) -> int:
    e = _engine()
    ok = _print_checks(e.verify_environment())
    s = e.safety
    print("blocked:", s.blocked())
    print("active fault marker:", s.active())
    print("lock holder:", s.holder())
    return 0 if ok else 1


def cmd_seed(a) -> int:
    """Exercise the real document workflow: upload -> consume -> searchable."""
    c = PaperlessClient(timeout=15)
    ok_all = True
    for i in range(a.count):
        res, task = c.upload_document()
        print(f"upload {i + 1}: ok={res.ok} {res.detail} ({res.latency_ms:.0f}ms)")
        if not task:
            ok_all = False
            continue
        t0 = time.time()
        while time.time() - t0 < 120:
            st = c.task_status(task)
            if st and st.get("status") in ("success", "failure"):
                print(f"   processing: {st['status']} docs={st.get('related_document_ids')} "
                      f"after {time.time() - t0:.1f}s")
                ok_all &= st["status"] == "success"
                break
            time.sleep(1)
        else:
            print("   processing did not finish in 120s")
            ok_all = False
    print(c.probe_documents().detail)
    return 0 if ok_all else 1


def _follow(e: Engine, run_id: str) -> None:
    last = None
    try:
        while True:
            live = e.live()
            key = (live.get("state"), live.get("message"))
            if key != last:
                print(f"{time.strftime('%H:%M:%S')}  [{live.get('state')}] {live.get('message')}")
                last = key
            if live.get("state") in TERMINAL and not e.running_here():
                break
            time.sleep(0.5)
    except KeyboardInterrupt:
        print("\nCtrl-C: triggering kill switch ...")
        print(json.dumps(e.kill("Ctrl-C in CLI"), indent=2))
        e.wait(120)


def cmd_baseline(a) -> int:
    e = _engine()
    e.recover_on_startup()
    try:
        run_id = e.start_baseline(a.duration)
    except ExperimentRejected as ex:
        print("rejected:", ex.errors)
        return 2
    print("baseline run", run_id)
    _follow(e, run_id)
    run = e.store.get_run(run_id)
    for probe, st in run["summary"]["metrics"].get("baseline", {}).get("probes", {}).items():
        er = "n/a" if st["error_rate"] is None else f"{st['error_rate']:.0%}"
        print(f"  {probe:<15} n={st['n']:<4} errors={er:<5} p50={st['p50_ms'] or 0:.0f}ms p95={st['p95_ms'] or 0:.0f}ms")
    return 0 if run["state"] == "completed" else 1


def cmd_run(a) -> int:
    e = _engine()
    e.recover_on_startup()
    try:
        cfg = ExperimentConfig(
            name=a.name, hypothesis=a.hypothesis, fault_type=a.fault, target=a.target,
            duration_s=a.duration, latency_ms=a.latency_ms,
            thresholds=Thresholds(max_error_rate=a.max_error_rate, max_p95_latency_ms=a.max_p95_ms,
                                  window_s=a.window, min_samples=a.min_samples),
        )
    except Exception as ex:  # noqa: BLE001
        print("invalid config:", ex)
        return 2
    try:
        run_id = e.start(cfg)
    except ExperimentRejected as ex:
        print("REJECTED:")
        for err in ex.errors:
            print("  -", err)
        return 2
    print("experiment", run_id)
    _follow(e, run_id)
    print()
    print(format_report(e.store.get_run(run_id)))
    return 0


def cmd_kill(a) -> int:
    store = Store()
    SafetyState(store).request_kill("CLI kill command")
    try:  # tell a running API server too, if there is one
        import httpx
        r = httpx.post(f"http://127.0.0.1:{config.CONTROLLER_PORT}/api/kill", timeout=60)
        print("server kill:", r.json())
    except Exception as ex:  # noqa: BLE001
        print(f"(controller API not reachable: {type(ex).__name__})")
    spec = SafetyState(store).active()
    ok, notes = emergency_rollback(Docker(), spec)
    print("local rollback:", "verified" if ok else "UNVERIFIED", notes)
    if ok:
        SafetyState(store).clear_active()
    return 0 if ok else 1


def cmd_rollback(a) -> int:
    store = Store()
    s = SafetyState(store)
    ok, notes = emergency_rollback(Docker(), s.active())
    store.event("manual_rollback", ("verified: " if ok else "UNVERIFIED: ") + "; ".join(notes))
    print("rollback:", "verified" if ok else "UNVERIFIED", notes)
    if ok:
        s.clear_active()
    else:
        s.block("manual rollback could not be verified", None)
    return 0 if ok else 1


def cmd_unblock(a) -> int:
    ok, checks = _engine().unblock()
    _print_checks(checks)
    print("unblocked" if ok else "still blocked")
    return 0 if ok else 1


def _out(text: str, path: str | None = None) -> None:
    if path:
        from pathlib import Path
        Path(path).write_text(text + "\n", encoding="utf-8")
        print(f"written to {path}")
    else:
        print(text)


def cmd_report(a) -> int:
    store = Store()
    if a.run_id == "findings":
        _out(pipeline.full_report(store, Docker()), a.out)
        return 0
    run = (store.latest_run("experiment") if a.run_id == "latest" else store.get_run(a.run_id))
    if not run:
        print("no such run")
        return 1
    analysis = store.get_analysis(run["id"])
    _out(format_report(run) + ("\n" + format_analysis(analysis) if analysis else
                               "\n\n(not analysed yet: python -m chaos analyze " + run["id"] + ")"), a.out)
    return 0


